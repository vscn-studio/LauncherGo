async function call(path, cookie, body, method = body === undefined ? 'GET' : 'POST', extra = {}) {
  const response = await fetch(api + path, { method, headers: { ...(cookie ? {Cookie:cookie} : {}), ...(body !== undefined ? {'Content-Type':'application/json','X-ServerMap-Request':'1'} : {}), ...extra }, body: body === undefined ? undefined : JSON.stringify(body) });
  const bytes = Buffer.from(await response.arrayBuffer());
  return { status:response.status, headers:response.headers, bytes, json:() => JSON.parse(bytes.toString()) };
}
function pixel(png,x,y) {
  let offset=8; const parts=[];
  while(offset+12<=png.length){const length=png.readUInt32BE(offset),type=png.toString('ascii',offset+4,offset+8);if(type==='IDAT')parts.push(png.subarray(offset+8,offset+8+length));offset+=12+length;}
  const rgba=zlib.inflateSync(Buffer.concat(parts)),start=y*(512*4+1)+1+x*4;return [...rgba.subarray(start,start+4)];
}
